#[cold]
#[inline(never)]
fn resolve_family_kerning_fallback(family: &str) -> (FontMetricProfile, &'static CsrKerningTable) {
    if is_monospace_family(family) {
        return (FontMetricProfile::MONOSPACE, &UNIVERSAL_SANS_CSR_LUT);
    }
    if contains_ascii_case_insensitive(family, b"lm roman")
        || contains_ascii_case_insensitive(family, b"latin modern roman")
    {
        (FontMetricProfile::LM_ROMAN, &LM_ROMAN_CSR_LUT)
    } else if contains_ascii_case_insensitive(family, b"computer modern") {
        (FontMetricProfile::LM_ROMAN, &UNIVERSAL_SERIF_CSR_LUT)
    } else if contains_ascii_case_insensitive(family, b"lm sans")
        || contains_ascii_case_insensitive(family, b"latin modern sans")
    {
        (FontMetricProfile::LM_SANS, &LM_SANS_CSR_LUT)
    } else if contains_ascii_case_insensitive(family, b"segoe") {
        (FontMetricProfile::SEGOE_UI, &UNIVERSAL_SANS_CSR_LUT)
    } else if contains_ascii_case_insensitive(family, b"calibri") {
        (FontMetricProfile::CALIBRI, &UNIVERSAL_SANS_CSR_LUT)
    } else if contains_ascii_case_insensitive(family, b"roboto")
        || contains_ascii_case_insensitive(family, b"noto sans")
        || contains_ascii_case_insensitive(family, b"inter")
    {
        (FontMetricProfile::ROBOTO, &UNIVERSAL_SANS_CSR_LUT)
    } else if contains_ascii_case_insensitive(family, b"vollkorn") {
        (FontMetricProfile::VOLLKORN, &UNIVERSAL_SERIF_CSR_LUT)
    } else if contains_ascii_case_insensitive(family, b"minion") {
        (FontMetricProfile::MINION_PRO, &UNIVERSAL_SERIF_CSR_LUT)
    } else if contains_ascii_case_insensitive(family, b"crimson") {
        (FontMetricProfile::CRIMSON_PRO, &UNIVERSAL_SERIF_CSR_LUT)
    } else if contains_ascii_case_insensitive(family, b"sans")
        || contains_ascii_case_insensitive(family, b"arial")
        || contains_ascii_case_insensitive(family, b"helvetica")
    {
        (FontMetricProfile::DEFAULT_SANS, &UNIVERSAL_SANS_CSR_LUT)
    } else {
        (FontMetricProfile::DEFAULT_SERIF, &UNIVERSAL_SERIF_CSR_LUT)
    }
}

/// Resolves both the metric profile and the static L1 CSR kerning table in a single zero-allocation pass.
#[inline(always)]
pub fn resolve_family_kerning(family: &str) -> (FontMetricProfile, &'static CsrKerningTable) {
    match family {
        "LM Sans Serif" | "LM Sans Bold" | "Latin Modern Sans" => {
            (FontMetricProfile::LM_SANS, &LM_SANS_CSR_LUT)
        }
        "LM Roman" | "LM Roman Bold" | "Latin Modern Roman" => {
            (FontMetricProfile::LM_ROMAN, &LM_ROMAN_CSR_LUT)
        }
        "LM Typewriter"
        | "LM Typewriter Bold"
        | "Consolas"
        | "Cascadia Mono"
        | "Cascadia Code"
        | "Courier New" => (FontMetricProfile::MONOSPACE, &UNIVERSAL_SANS_CSR_LUT),
        "Segoe UI" => (FontMetricProfile::SEGOE_UI, &UNIVERSAL_SANS_CSR_LUT),
        "Calibri" => (FontMetricProfile::CALIBRI, &UNIVERSAL_SANS_CSR_LUT),
        "Arial" => (FontMetricProfile::DEFAULT_SANS, &UNIVERSAL_SANS_CSR_LUT),
        "Georgia" | "Tahoma" | "Verdana" => {
            (FontMetricProfile::DEFAULT_SERIF, &UNIVERSAL_SERIF_CSR_LUT)
        }
        _ => resolve_family_kerning_fallback(family),
    }
}

#[inline(always)]
pub fn profile_for_family(family: &str) -> FontMetricProfile {
    resolve_family_kerning(family).0
}

/// SOTA 1D SVD Sidebearing Profile:
/// Captures dominant rank-1 marginal vectors (R + L) with zero heap churn.
/// Memory footprint: exactly 192 bytes per font.
#[derive(Clone, Copy)]
pub struct Svd1dKerningProfile {
    pub mu: i16,
    pub r_adjust: &'static [i8; 95],
    pub l_adjust: &'static [i8; 95],
}

impl Svd1dKerningProfile {
    pub const fn new(mu: i16, r_adjust: &'static [i8; 95], l_adjust: &'static [i8; 95]) -> Self {
        Self { mu, r_adjust, l_adjust }
    }

    /// Infers generalized kerning value in design units with cubic Hermite deadband filtering.
    #[inline(always)]
    // wiring-ok: CounterSpace cavity-sealing inference engine verified against CSR tables
    pub fn infer(&self, c1: char, c2: char) -> Option<i16> {
        let b1 = canonical_base_char(c1) as u32;
        let b2 = canonical_base_char(c2) as u32;
        if b1 < 32 || b1 > 126 || b2 < 32 || b2 > 126 {
            return None;
        }
        let r = (b1 - 32) as usize;
        let c = (b2 - 32) as usize;
        let raw = self.mu + (self.r_adjust[r] as i16) + (self.l_adjust[c] as i16);
        let abs_raw = raw.abs();
        if abs_raw < 14 {
            None
        } else if abs_raw < 28 {
            let t = (abs_raw - 14) as f32 * (1.0_f32 / 14.0_f32);
            let t2 = t * t;
            let smooth = (3.0_f32 * t2 - 2.0_f32 * t2 * t) * (abs_raw as f32);
            let signed = if raw < 0 { -smooth } else { smooth };
            Some((signed + f32::copysign(0.5_f32, signed)) as i16)
        } else {
            Some(raw)
        }
    }
}

