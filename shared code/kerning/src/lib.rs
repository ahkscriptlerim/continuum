/// Computes the physical diacritic overhang damping factor ∈ [0.35, 1.0] for accented pairs.
/// Prevents top cantilevers (`T`, `F`, `f`) from colliding with high diacritics (`ä`, `î`, `ï`, `č`)
/// while leaving bottom-wide pyramids (`A` + `ä`) 100% undamped.
#[inline(always)]
pub fn diacritic_overhang_damping(c1: char, c2: char) -> f32 {
    if c1.is_ascii() && c2.is_ascii() {
        return 1.0_f32;
    }
    let b1 = canonical_base_char(c1);
    let b2 = canonical_base_char(c2);

    // 1. Top-right cantilever/hook (T, F, P, f) overhanging a lowercase vowel with a high diacritic
    if matches!(b1, 'T' | 'F' | 'P' | 'f') && has_upper_diacritic_lowercase(c2) {
        if b2 == 'i' {
            // Narrow 'i' with wide diaeresis/circumflex/macron (ï, î, ī) collides severely with T/F/f crossbar
            return 0.35_f32;
        }
        return 0.72_f32;
    }
    // 2. Narrow accented lowercase (í, î, ï, ī, ď, ť, ľ) preceding a top-left overhanging capital/delimiter
    if has_upper_diacritic_lowercase(c1) && matches!(b1, 'i' | 'd' | 't' | 'l') && matches!(b2, 'T' | 'V' | 'W' | 'Y' | '?' | '!' | ')' | ']' | '}') {
        return 0.50_f32;
    }
    // 3. Lower diacritic (cedilla/ogonek/comma-below: ç, ą, ę, ş, ț) adjacent to descender or baseline dot
    if (has_lower_diacritic(c1) && matches!(b2, 'g' | 'j' | 'p' | 'q' | 'y' | '.' | ','))
        || (matches!(b1, 'g' | 'j' | 'p' | 'q' | 'y' | '.' | ',') && has_lower_diacritic(c2))
    {
        return 0.55_f32;
    }
    1.0_f32
}

/// Zero-allocation ASCII case-insensitive substring matcher.
/// `needle_lower` MUST contain lowercase ASCII bytes (`a..=z` or non-uppercase ASCII).
#[inline(always)]
pub fn contains_ascii_case_insensitive(haystack: &str, needle_lower: &[u8]) -> bool {
    let n = needle_lower.len();
    if n == 0 {
        return true;
    }
    let hb = haystack.as_bytes();
    if hb.len() < n {
        return false;
    }
    // SAFETY: `n >= 1` and `hb.len() >= n`.
    let first = unsafe { *needle_lower.get_unchecked(0) };
    let limit = hb.len() - n;
    let mut i = 0usize;
    while i <= limit {
        // SAFETY: `i <= hb.len() - n` and `n >= 1`, so `i + j < hb.len()` for all `j < n`.
        if unsafe { *hb.get_unchecked(i) }.to_ascii_lowercase() == first {
            let mut j = 1usize;
            while j < n {
                let hc = unsafe { *hb.get_unchecked(i + j) }.to_ascii_lowercase();
                let nc = unsafe { *needle_lower.get_unchecked(j) };
                if hc != nc {
                    break;
                }
                j += 1;
            }
            if j == n {
                return true;
            }
        }
        i += 1;
    }
    false
}

/// Checks whether a font family is fixed-pitch monospace.
/// Strictly enforces the Monospace Invariant: zero tracking, zero kerning.
#[inline(always)]
pub fn is_monospace_family(name: &str) -> bool {
    match name {
        "LM Typewriter"
        | "LM Typewriter Bold"
        | "Consolas"
        | "Cascadia Mono"
        | "Cascadia Code"
        | "Courier New" => true,
        "LM Sans Serif"
        | "LM Sans Bold"
        | "LM Roman"
        | "LM Roman Bold"
        | "Segoe UI"
        | "Calibri"
        | "Arial"
        | "Georgia"
        | "Tahoma"
        | "Verdana" => false,
        _ => {
            contains_ascii_case_insensitive(name, b"mono")
                || contains_ascii_case_insensitive(name, b"typewriter")
                || contains_ascii_case_insensitive(name, b"code")
                || contains_ascii_case_insensitive(name, b"consolas")
                || contains_ascii_case_insensitive(name, b"courier")
                || contains_ascii_case_insensitive(name, b"fixed")
                || contains_ascii_case_insensitive(name, b"terminal")
        }
    }
}

